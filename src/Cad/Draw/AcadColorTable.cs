    /// <summary>索引 → (R,G,B) 0..255；越界给白色（同原版 GetColor）。</summary>
    public static (byte r, byte g, byte b) Rgb255(int index)
    {
        if (index < 1 || index > 255) return (255, 255, 255);
        return (Table[index, 0], Table[index, 1], Table[index, 2]);
    }

    /// <summary>索引 → 0..1 浮点 RGB（场景实体存的就是这个）。</summary>
    public static (float r, float g, float b) RgbF(int index)
    {
        var (r, g, b) = Rgb255(index);
        return (r / 255f, g / 255f, b / 255f);
    }

    /// <summary>RGB → 最接近的 ACI 索引（同原版 FindNearestIndex：欧氏距离最小者，并列取小号）。</summary>
    public static int NearestIndex(byte r, byte g, byte b)
    {
        int best = 7;
        double bestDist = double.MaxValue;
        for (int i = 1; i <= 255; i++)
        {
            double dr = r - Table[i, 0], dg = g - Table[i, 1], db = b - Table[i, 2];
            double d = dr * dr + dg * dg + db * db;
            if (d < bestDist) { bestDist = d; best = i; }
        }
        return best;
    }

    /// <summary>浮点 RGB → 最接近的 ACI 索引。</summary>
    public static int NearestIndex(float r, float g, float b) => NearestIndex(
        (byte)Math.Round(Math.Clamp(r, 0, 1) * 255),
        (byte)Math.Round(Math.Clamp(g, 0, 1) * 255),
        (byte)Math.Round(Math.Clamp(b, 0, 1) * 255));
