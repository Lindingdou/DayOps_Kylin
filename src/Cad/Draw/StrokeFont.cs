namespace PitMine3D.Kylin.Cad.Draw;

/// <summary>
/// 单笔画矢量字体 —— 数字/字母/常用符号绘成线段，供 GL 线管线渲染文字，无需 Skia。
/// 覆盖 0-9、A-Z(大小写折叠)、. - + : / 空格。中文字形需字库(记录待做)。
/// 坐标在单位盒内：宽 0.6、高 1.0。纯逻辑、可单测。
/// </summary>
public static class StrokeFont
{
    private const int A = 1, B = 2, C = 4, D = 8, E = 16, F = 32, G = 64;   // 7 段
    private static readonly Dictionary<char, int> Digit = new()
    {
        ['0'] = A | B | C | D | E | F, ['1'] = B | C, ['2'] = A | B | G | E | D, ['3'] = A | B | G | C | D,
        ['4'] = F | G | B | C, ['5'] = A | F | G | C | D, ['6'] = A | F | G | E | D | C, ['7'] = A | B | C,
        ['8'] = A | B | C | D | E | F | G, ['9'] = A | B | C | D | F | G,
    };

