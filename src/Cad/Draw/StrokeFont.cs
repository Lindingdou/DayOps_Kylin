    /// <summary>字符 → 单位盒内的线段（x0,y0,x1,y1）；未知字符返回空。</summary>
    public static List<(double x0, double y0, double x1, double y1)> Strokes(char c)
    {
        var s = new List<(double, double, double, double)>();
        if (Digit.TryGetValue(c, out int mask))
        {
            if ((mask & A) != 0) s.Add((0, 1, 0.6, 1));
            if ((mask & B) != 0) s.Add((0.6, 1, 0.6, 0.5));
            if ((mask & C) != 0) s.Add((0.6, 0.5, 0.6, 0));
            if ((mask & D) != 0) s.Add((0, 0, 0.6, 0));
            if ((mask & E) != 0) s.Add((0, 0.5, 0, 0));
            if ((mask & F) != 0) s.Add((0, 1, 0, 0.5));
            if ((mask & G) != 0) s.Add((0, 0.5, 0.6, 0.5));
            return s;
        }
        char u = c >= 'a' && c <= 'z' ? (char)(c - 32) : c;
        if (Letters.TryGetValue(u, out var seg))
        {
            for (int i = 0; i + 3 < seg.Length; i += 4) s.Add((seg[i], seg[i + 1], seg[i + 2], seg[i + 3]));
            return s;
        }
        switch (c)
        {
            case '-': s.Add((0, 0.5, 0.6, 0.5)); break;
            case '+': s.Add((0, 0.5, 0.6, 0.5)); s.Add((0.3, 0.8, 0.3, 0.2)); break;
            case '.': s.Add((0.25, 0, 0.35, 0)); break;
            case ':': s.Add((0.3, 0.7, 0.3, 0.6)); s.Add((0.3, 0.4, 0.3, 0.3)); break;
            case '/': s.Add((0, 0, 0.6, 1)); break;
            case '=': s.Add((0, 0.62, 0.6, 0.62)); s.Add((0, 0.38, 0.6, 0.38)); break;   // 等号(补, 供坐标标注 X=)
            case '°':   // 度符号: 顶部小圈(六边近似)
                s.Add((0.30, 0.95, 0.15, 0.87)); s.Add((0.15, 0.87, 0.15, 0.73)); s.Add((0.15, 0.73, 0.30, 0.65));
                s.Add((0.30, 0.65, 0.45, 0.73)); s.Add((0.45, 0.73, 0.45, 0.87)); s.Add((0.45, 0.87, 0.30, 0.95));
                break;
            case 'Ø':   // 直径符号: 竖六边形(≈圆) + 斜杠
                s.Add((0.30, 1, 0.05, 0.75)); s.Add((0.05, 0.75, 0.05, 0.25)); s.Add((0.05, 0.25, 0.30, 0));
                s.Add((0.30, 0, 0.55, 0.25)); s.Add((0.55, 0.25, 0.55, 0.75)); s.Add((0.55, 0.75, 0.30, 1));
                s.Add((0.05, 0.15, 0.55, 0.85));
                break;
        }
        return s;
    }
}
