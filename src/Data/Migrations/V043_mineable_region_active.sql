-- =============================================================================
-- V043: 作业区域的「本期选定」(mineable_region.active)
--
-- 由来:mineable_region 已经是全项目共用的作业区域注册表 —— 三维推演拿它当推进轮廓
--   (SimRegionLoader.Load 的第一顺位)、路网中心线提取拿它当裁剪范围
--   (RoadLibPlugin.LoadClipRegions)。但两处都是 svc.All() **全表取**,
--   于是"这一期到底在哪几块作业"这件事在库里没有落点:
--   历史遗留的老采场、下一期才启用的排土场,只要在表里就一起进推演、一起参与裁剪。
--
-- 【为什么不复用 visible】visible 是「在视口上画不画它」,是显示开关。
--   拿它兼做"算不算数",就会出现:有人为了看图清爽把一块隐掉 →
--   推演里那块区域**静默消失**、路网裁剪范围**静默缩小**,而界面上没有任何提示。
--   显示与参与计算是两件事,必须两列。
--
-- 【为什么 DEFAULT 1】既有库升级后所有区域仍是"选定"状态 —— 行为与升级前完全一致。
--   若默认 0,用户升级后一开程序会发现推演里一块区域都没有,却找不到原因。
--   新增区域也默认选定:画一块出来就是要用它,让人再点一次纯属多余。
--
-- 【消费方的口径】只有【自动全表取】的两处按本列过滤:
--     · SimRegionLoader.Load     —— 推演的推进轮廓
--     · RoadLibPlugin.LoadClipRegions —— 中心线提取的裁剪范围
--   两处都必须把"因未选定而排除了 N 块"如实写进各自的来源文案 ——
--   静默少几块正是本列要消灭的问题,不能换个理由再犯一次。
--   而【由人按名字挑一块】的接口(CarveStripModelForRegion、两期填挖方的区域清单等)
--   一律不过滤:未选定 ≠ 这块区域不存在了。
--
-- 幂等:照抄 V036/V037 的裸 ALTER TABLE ADD COLUMN,不自创 guard。
--   迁移器按 (module, version) 主键只跑一次,并按 checksum 校验已应用脚本。
-- ★ 不改既有脚本:改动一个字都会抛 MigrationChecksumMismatchException,让用户的库起不来。
-- =============================================================================

-- ── 本期是否纳入作业范围(1=选定,进推演/进路网裁剪;0=不参与,但仍在台账里) ───────────
ALTER TABLE mineable_region ADD COLUMN active INTEGER NOT NULL DEFAULT 1;
