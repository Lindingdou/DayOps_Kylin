-- V046: 排土场台账 ↔ 作业区域 的桥(dump_site.region_id)
--
-- 由来:系统里"排土场"一直有【两个互不认识的身份】——
--     几何侧:mineable_region(category = external_dump / internal_dump),
--            「采场/排土场圈定」落的,带 points_json;
--            【排土条带】的下拉列的就是它,产出的 dump_strip 记的是 region_id。
--     台账侧:dump_site(dump_id),带设计容量 / 堆高 / 坡角 / 服务年限;
--            「去向台账」维护,【逐月排土配对】的库容条与超容预警读的是它的
--            design_capacity_wan_m3。
--   两张表之间**一列关联都没有**。于是"条带算出来的几何库容"和"台账里的设计容量",
--   连是不是同一个排土场都无从判断 —— 这正是【排土场容量校核】一直做不下去的原因:
--   它要对的两个数,分属两条没接上的链。
--
-- 【为什么加在 dump_site 这边】dump_site 是"身份 + 参数",region 是"它的范围"。
--   一个排土场对应一块几何范围,方向天然是 dump_site → region。
--   反过来在 mineable_region 上加 dump_id 也能通,但 mineable_region 是全项目共用的
--   作业区域注册表(采场、工作帮、内外排都在里面),给它加一列只对其中两类有意义的外键,
--   会让"这一列该不该填"变成每种类别各一套说法。
--
-- 【为什么可空、且不加外键约束】
--   · 可空:既有库里两边都已经有数据,升级后一条都不该被强制配对 —— 谁跟谁是一对,
--     只有人知道。不填 = 还没挂上,行为与升级前完全一致。
--   · 不加 FOREIGN KEY:mineable_region 的行会被「圈定」重画、删除重建,
--     硬外键会让删一块区域这件事连带失败或级联删掉台账 —— 台账不该跟着几何走。
--     悬空的 region_id(指向已删区域)按"没挂上"处理,由消费方自己判。
--
-- 【消费方的口径】挂上之后这条链才成立:
--     dump_id → region_id → points_json      台账终于有几何,容量校核能拿条带的
--                                            ΣCapacityM3 去对 design_capacity_wan_m3
--     region_id → dump_id                    条带产出的位置清单能反查到是哪个场
--   ⚠ 未挂上时**不许猜**(比如按名字模糊匹配):猜错一个场,库容对账的两个数就分别属于
--     两个排土场,而算出来的差额看着完全正常。没挂上就如实报"没挂上"。
--
-- 幂等:照抄 V036/V037/V043 的裸 ALTER TABLE ADD COLUMN,不自创 guard。
--   迁移器按 (module, version) 主键只跑一次,并按 checksum 校验已应用脚本。
