--
-- 变换:
--   new_x = old_y - 37000000   旧 y = 经距(含 37 带号, ~3.76e7) → 去带号后的经距(~6.2e5)
--   new_y = old_x              旧 x = 纬距(~4.4e6) → 作为新 y
--   （SQLite 的 SET 右值取行的原始值，单条 UPDATE 即可正确交换）
--
-- 幂等保护: WHERE y > 37000000 —— 只处理仍是旧格式(y 含带号 > 37e6)的行；
--   变换后 y = 纬距(~4.4e6 < 37e6)，重复执行不会被再次处理。
--
-- 动机: 旧 y 含 37 带号达 3.76e7，float32 在 GPU/渲染端 ULP≈4m，导致 3D 渲染
--   抖动、小包围盒被视锥误剔。去带号后坐标降到 X~6.2e5 / Y~4.4e6，精度大幅改善。
--
-- 注意: 校验和保护下本脚本一经应用不可再改；如需再调坐标请新增 V015。
-- =============================================================================

UPDATE borehole
   SET x = y - 37000000,
       y = x
 WHERE y > 37000000;

UPDATE coal_observation_point
   SET x = y - 37000000,
       y = x
