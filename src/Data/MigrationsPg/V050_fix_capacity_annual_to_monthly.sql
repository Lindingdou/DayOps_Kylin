-- V050: 修正设备能力的年/月口径 —— V020~V022 把「台年能力」当成了「月产量」。
--
-- ── 事实 ──────────────────────────────────────────────────────────────────────
-- 源表：7.1\2023年-2026年5月露天矿设备能力、单耗统计表\*\*设备能力分析.xlsx
--   「2026设备能力」sheet 列头：矿别|环节|厂家|型号|租赁数量|在籍数量|计划能力（万m³）|1月|2月…
--   同工作簿「分设备比较(计划)」sheet 的同一列叫【台年理论生产能力 / 计划台年能力，单位 万m³】。
--   ⇒ 逐月列不是「当月产量」，是【当月实际折算出来的台年能力，万m³/台·年】，而且是**单台**值。
--   验证（安太堡采装 2026-05 小计）：3×927.84(4100XPC) + 2×418.2(WK-35) + 330.96 + 41.4 = 3992.28
--   = 表里的小计行，分毫不差 ⇒ 逐月列确实是单台台年能力，小计 = Σ(台数 × 台均)。
--
-- V021 把这个数 ×1e4 直接写进了 capacity_monthly.output_m3 并当作【m³/月】：
--   原表 DMH90 270.7 → 库 2,707,200 ｜ YZ35C 912.9 → 9,129,185 ｜ KY250B 1050.0 → 10,500,000
--   PH2800XPB 626.6 → 6,265,600 ｜ WK-55 963.2 → 9,631,800 ｜ EH-3500 73.6 → 736,000
--   —— 逐型号逐字节相同，不是"某一行录错"，是整张表错了一个口径。
-- V020 的 equipment_model.std_daily_cap_wan_m3 是同一个错的另一种折法：台年能力 ÷ 30 天，
--   标成「万m³/日」（730E：2.5208 × 30 = 75.6 = 原表三矿按台数加权的台年能力 75.6）。
-- V022 的 production_record 又是从 V021 的月量按日历天/班摊出来的（2026-05 的 11 天）。
--
-- ── 后果 ──────────────────────────────────────────────────────────────────────
-- EquipmentFleetProvider 拿 output_m3 ÷ 作业日(25) 当日台效 ⇒ 4100XPC 得 357,600 m³/台·日。
-- 该机斗容 60.6m³、回转 0.53min/斗，24h 满负荷不检修不等车的**物理极限**约 93,000 m³/日 ——
-- 现值是极限的 3.8 倍。全矿电铲 2026-05 合计 2.36 亿 m³/月，而三矿全年采剥量才是这个量级。
--
-- ── 修正 ──────────────────────────────────────────────────────────────────────
-- 年 → 月：全部 ÷ 12。修正后 4100XPC = 30,900 m³/台·日（物理极限的 33%），
-- 落回 EquipmentFleetProvider.PlausibleLoaderDayLo/Hi (3000~60000) 这条带内。
--
-- 为什么不改 V021/V020 本身：那两个脚本已应用，改一个字节校验和就对不上，
-- GeoDataBasePlugin.Initialize 直接抛 ⇒ 整个数据库层下线，界面上只表现为"台账未接通"。
--
-- 每条 UPDATE 都带 EXISTS 守卫（判的是"库里还存在物理上不可能的值"），
-- 所以**重复执行是 no-op**；全新库上 V021→V050 顺序执行，结果一致。
-- 口径若哪天换回年制，守卫会自己重新成立 —— 它判的是数据本身，不是有没有跑过。

-- ① 月度产能：台年能力(万m³/年)×1e4 → 月产量(m³/月)
--    守卫：单台单月 > 200 万 m³ 在露天矿是不可能的（最大的 4100XPC 满打满算 ~90 万/月）。
UPDATE capacity_monthly SET output_m3 = output_m3 / 12.0
WHERE EXISTS (
    SELECT 1 FROM capacity_monthly cm2
    JOIN equipment e ON e.equipment_id = cm2.equipment_id
    WHERE e.category IN ('Shovel', 'Loader') AND cm2.output_m3 > 2000000
);

-- ② 型号字典的标准日产能：原值 = 台年能力 ÷ 30，语义应是「万m³/日」
--    守卫：单机 > 10 万 m³/日 不可能（÷12 后最大的 WK-55 是 2.74 万m³/日）。
UPDATE equipment_model SET std_daily_cap_wan_m3 = std_daily_cap_wan_m3 / 12.0
WHERE std_daily_cap_wan_m3 IS NOT NULL
  AND EXISTS (SELECT 1 FROM equipment_model WHERE std_daily_cap_wan_m3 > 10);

-- ③ 班产记录：从 ① 的月量摊出来的，同错同倍
--    守卫：单班 > 3 万 m³ 不可能（÷12 后最大 1.5 万/班）。
--    ⚠ 这一步只修**量级**。production_record 还有一个独立问题没修：
--      同一批方量在电铲/卡车/钻机/前装机四类设备上各记了一遍（2026-05 四类各 8000 万m³ 上下），
--      所以它**不能当实绩量的可信源**用 —— 实绩一律走 actuals/。
UPDATE production_record SET output_m3 = output_m3 / 12.0
WHERE EXISTS (SELECT 1 FROM production_record WHERE output_m3 > 30000);
